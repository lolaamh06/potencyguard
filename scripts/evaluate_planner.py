"""Honest evaluation of the decision planner (Phase 5): writes docs/02-phase-reports/phase-05-evaluation.md.

Run from the repo root:  python scripts/evaluate_planner.py

Everything here is a simulation result on a synthetic box. All money values, probabilities, delays
and thresholds are illustrative placeholders, not sourced [SOURCE NEEDED]. The planner is only as
good as the potency estimate, the thermal twin (single-node; Phase 3C showed it does not represent a
box with a payload, a richer twin is on the backlog as Phase 3D) and its own placeholder
assumptions. It is NOT validated against real decisions. It recommends; it never executes.
"""
# ruff: noqa: E501  (report text lines)

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from planner.cli import DEMO_CHECKPOINTS, RECORDINGS  # noqa: E402
from planner.config import load_planner_config  # noqa: E402
from planner.core import plan  # noqa: E402
from planner.cvar import cvar_discrete, expected_discrete  # noqa: E402
from planner.governance import build_decision  # noqa: E402
from planner.pipeline import build_inputs  # noqa: E402
from shared.config import load_box_config, load_product_config  # noqa: E402

OUT = REPO_ROOT / "docs" / "02-phase-reports" / "phase-05-evaluation.md"
FOOTER = "Simulation result on a synthetic box. Not real-world evidence."
SWEEP_V = (10_000, 25_000, 50_000, 100_000, 200_000)
SWEEP_BETA = (0, 100, 200, 500, 1000)
SWEEP_CASES = (("reefer_failure", 20.0), ("heatwave_transit", 40.0), ("hidden_spoilage", 50.0))
EXTRA_SEEDS = tuple(range(1, 10))


def tbl(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + [
        "| " + " | ".join(str(c) for c in r) + " |" for r in rows
    ]


def why(decision, table) -> str:
    c = table.results["continue"]
    best = table.results[decision.chosen_action]
    parts = []
    inputs = decision.inputs
    if inputs.bound_used:
        parts.append(
            f"the readings are {inputs.trust_level}, so the plan starts from the worst-case bound "
            f"(tau_eq {inputs.start_tau_eq_h:,.0f} h instead of {inputs.tau_eq_now_h:,.0f} h)"
        )
    if decision.chosen_action == "continue":
        if c.failure_probability >= 0.5:
            parts.append(
                f"continuing fails in {c.failure_probability * 100:.0f} percent of scenarios, "
                "but so does every cheaper-than-replacement action, and continuing is the cheapest"
            )
        else:
            parts.append(
                f"continuing fails in {c.failure_probability * 100:.1f} percent of scenarios"
            )
    else:
        parts.append(
            f"continuing would fail in {c.failure_probability * 100:.1f} percent of scenarios "
            f"(bad-case loss {c.cvar:,.0f}); {decision.chosen_action} has bad-case loss {best.cvar:,.0f}"
        )
    return "; ".join(parts)


def main() -> int:
    cfg = load_planner_config()
    product, box = load_product_config(), load_box_config()
    lines = [
        "# Phase 5 evaluation (generated by scripts/evaluate_planner.py)",
        "",
        FOOTER,
        "",
        "All money values, probabilities, delays and thresholds are illustrative placeholders, "
        "not sourced [SOURCE NEEDED] (config/planner.yaml). The planner recommends; it never "
        "executes; final authority stays with QA. It is only as good as the potency estimate and "
        "the single-node thermal twin (which Phase 3C showed cannot represent a box with a payload; "
        "a richer twin, Phase 3D, is on the backlog), and it is NOT validated against real "
        "decisions.",
        "",
        "## 1. The oracle (master brief section 3.5, V = 50,000, alpha = 0.95)",
        "",
    ]
    outcomes = {
        "continue": [(0.0, 0.92), (50_000.0, 0.08)],
        "reroute": [(5_000.0, 0.995), (55_000.0, 0.005)],
    }
    lines += tbl(
        ["action", "cost", "failure prob", "expected loss", "CVaR 0.95"],
        [
            ["continue", "0", "8%", f"{expected_discrete(outcomes['continue']):,.0f}", f"{cvar_discrete(outcomes['continue'], 0.95):,.0f}"],
            ["reroute", "5,000", "0.5%", f"{expected_discrete(outcomes['reroute']):,.0f}", f"{cvar_discrete(outcomes['reroute'], 0.95):,.0f}"],
        ],
    )  # fmt: skip
    lines += [
        "",
        "Exact (analytic) values; the expected-loss-optimal action is continue and the CVaR-optimal action is reroute.",
        "",
    ]

    lines += [
        "## 2. The six demo scenarios at their checkpoints",
        "",
        f"Seed {cfg.seed}, {cfg.n_scenarios} scenarios per action, alpha {cfg.alpha}, V {cfg.V:,.0f}, "
        f"beta {cfg.beta:,.0f} per hour, V_thr {cfg.v_thr:,.0f}, confidence gap threshold "
        f"{cfg.confidence_gap_thr:,.0f}. The scheduled remaining time is the rest of the recording.",
        "",
    ]
    rows, details = [], []
    for name, hour in DEMO_CHECKPOINTS:
        built = build_inputs(RECORDINGS / f"{name}.jsonl", hour, product, box)
        table = plan(built.inputs, cfg, product, built.twin, built.setpoint_c)
        decision = build_decision(table, built.inputs, cfg)
        chosen = table.results[decision.chosen_action]
        rows.append([
            name, f"{hour:.0f}", f"{built.inputs.potency_now * 100:.2f}%", built.inputs.trust_level,
            built.inputs.verdict, decision.chosen_action, decision.expected_optimal_action,
            "yes" if decision.disagree else "no",
            f"{table.results['continue'].failure_probability * 100:.1f}%",
            f"{chosen.var:,.0f}", f"{chosen.cvar - chosen.expected_loss:,.0f}",
            decision.route, decision.shipment_status,
        ])  # fmt: skip
        details.append((name, hour, built, table, decision))
    lines += tbl(
        ["scenario", "hour", "potency now", "trust", "verdict", "CVaR-optimal", "expected-optimal",
         "disagree", "continue fails", "VaR (chosen)", "CVaR - mean (chosen)", "route", "status"],
        rows,
    )  # fmt: skip
    lines += ["", "Why, in plain words:", ""]
    for name, hour, _built, table, decision in details:
        lines.append(
            f"- **{name}** (hour {hour:.0f}): {why(decision, table)}. Route: {decision.route}."
        )
    lines += ["", "### The tables behind the six rows", ""]
    for name, hour, _built, table, _decision in details:
        lines += [f"**{name}, hour {hour:.0f}**", ""]
        lines += tbl(
            ["action", "cost", "fail prob", "expected loss", "VaR", "CVaR", "mean delay (h)"],
            [
                [a, f"{r.cost:,.0f}", f"{r.failure_probability * 100:.1f}%", f"{r.expected_loss:,.0f}", f"{r.var:,.0f}", f"{r.cvar:,.0f}", f"{r.mean_delay_h:.1f}"]
                for a, r in table.results.items()
            ],
        )  # fmt: skip
        lines.append("")

    lines += [
        "### Cases where the planner looks odd (reported, not hidden)",
        "",
        "- `spoof_attempt` and `hidden_spoilage` are untrusted, so the plan starts from the worst-case "
        "bound, which assumes no cooling after the doubt began. Almost every action then fails in "
        "nearly every scenario, and the recommendation falls to whichever action is cheapest or "
        "starts fresh (re_source). A person must decide in both cases; the recommendation is a "
        "pointer, not an answer.",
        "- In an untrusted case `continue` can be recommended although it fails in nearly every "
        "scenario: when every in-box action fails, the cheapest one has the smallest loss. The "
        "route is needs_human, which is the intended safeguard.",
        "- The first run of this evaluation showed a flaw that was fixed (decision 0009, P5 and P6): "
        "at hour 20 of `reefer_failure` (cooling already short of its job) the planner gave 0 "
        "percent failure for `continue` because it assumed working cooling and a cool ambient. "
        "Section 3 shows the effect of each fix.",
        "",
    ]

    lines += ["## 3. What the two modelling fixes change", ""]
    variants = (
        ("as shipped (anomaly handling on, persistence forecast)", {}),
        ("no anomaly handling (P5 off)", {"anomaly_cooling_fail_probability": 0.0}),
        (
            "fixed 22 degree ambient forecast (P6 off)",
            {"ambient": cfg.ambient.model_copy(update={"route_mean_mode": "fixed"})},
        ),
        (
            "both off (the first version)",
            {
                "anomaly_cooling_fail_probability": 0.0,
                "ambient": cfg.ambient.model_copy(update={"route_mean_mode": "fixed"}),
            },
        ),
    )
    rows = []
    for name, hour in (("reefer_failure", 20.0), ("heatwave_transit", 40.0)):
        built = build_inputs(RECORDINGS / f"{name}.jsonl", hour, product, box)
        for label, change in variants:
            table = plan(
                built.inputs, cfg.model_copy(update=change), product, built.twin, built.setpoint_c
            )
            c = table.results["continue"]
            rows.append(
                [
                    name,
                    label,
                    f"{c.failure_probability * 100:.1f}%",
                    f"{c.cvar:,.0f}",
                    table.cvar_optimal,
                ]
            )
    lines += tbl(["scenario", "model", "continue fails", "continue CVaR", "CVaR-optimal"], rows)
    lines += [
        "",
        "For reference, the recording of `reefer_failure` ends at about 86 percent potency (below "
        "the 90 percent limit) and `heatwave_transit` ends above it: the ambient is 41 to 48 degrees "
        "in both after the checkpoint. These recordings are one simulated path each, not a test of "
        "the planner's probabilities.",
        "",
    ]

    lines += ["## 4. Sensitivity to V and beta (illustrative)", ""]
    lines += [
        "Chosen (CVaR-optimal) action, with the approval route in brackets (A = auto_approved, H = needs_human). "
        "V is the value of goods plus replacement; beta is the price of an hour of delay. Both are placeholders; "
        "the table shows how much the recommendation depends on them, not what the right values are.",
        "",
    ]
    for name, hour in SWEEP_CASES:
        built = build_inputs(RECORDINGS / f"{name}.jsonl", hour, product, box)
        lines += [f"**{name}, hour {hour:.0f}**", ""]
        rows = []
        for v in SWEEP_V:
            row = [f"V = {v:,}"]
            for beta in SWEEP_BETA:
                c = cfg.model_copy(update={"V": float(v), "beta": float(beta)})
                table = plan(built.inputs, c, product, built.twin, built.setpoint_c)
                decision = build_decision(table, built.inputs, c)
                row.append(
                    f"{decision.chosen_action} ({'A' if decision.route == 'auto_approved' else 'H'})"
                )
            rows.append(row)
        lines += tbl(["", *[f"beta = {b}" for b in SWEEP_BETA]], rows)
        lines.append("")

    lines += ["## 5. Stability across seeds", ""]
    lines += [
        f"The same decision with the configured seed ({cfg.seed}) and nine other seeds. A recommendation "
        "that changes with the seed is a near-tie that sampling noise can flip (the CVaR of an action "
        "with rare failures rests on few scenarios).",
        "",
    ]
    rows = []
    for name, hour, built, _table, _decision in details:
        counts: dict[str, int] = {}
        for seed in (cfg.seed, *EXTRA_SEEDS):
            c = cfg.model_copy(update={"seed": seed})
            t = plan(built.inputs, c, product, built.twin, built.setpoint_c)
            counts[t.cvar_optimal] = counts.get(t.cvar_optimal, 0) + 1
        text = ", ".join(f"{a} {n} of 10" for a, n in sorted(counts.items(), key=lambda kv: -kv[1]))
        rows.append(
            [name, f"{hour:.0f}", text, "stable" if len(counts) == 1 else "VARIES WITH THE SEED"]
        )
    lines += tbl(["scenario", "hour", "CVaR-optimal over 10 seeds", "stable"], rows)
    lines += [
        "",
        "## 6. What this does and does not show",
        "",
        "- It shows that the pieces fit together: the planner reads the existing potency, trust and "
        "bound outputs, never starts from a point estimate when the readings are in doubt, sends "
        "doubtful cases to a person, and logs every decision in a signed, hash-chained log.",
        "- It does not show that the recommendations are right. The costs, V, beta, delays, cooling "
        "failure chances, ambient forecast and thresholds are placeholders; the sensitivity table "
        "shows the recommendation moves with them.",
        "- The thermal twin is a single-node model; on a box with a payload (Phase 3C) it is wrong in "
        "known ways. The persistence ambient forecast cannot foresee a change in the weather.",
        "- Signing protects records after signing; it does not stop a lie at the sensor (A18). The "
        "planner therefore uses the physics-based trust level, not the signature, to decide whether a "
        "reading may drive a decision.",
        "",
        FOOTER,
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
