// One typed model for all three modes. Field names are the real ones written by
// scripts/export_replay.py (see frontend-vision.md, amendment FV-A3); none is invented here.

export type Mode = "story" | "replay" | "live";

export type TrustLevel = "trusted" | "low_confidence" | "untrusted";

export interface FrameFlags {
  cusum: boolean;
  step: boolean;
  state: boolean;
  flat: boolean;
}

/** One sample of the sensor feed with the engine's outputs for that moment. */
export interface Frame {
  t_s: number;
  temp_c: number | null;
  ambient_c: number | null;
  twin_c: number | null;
  residual_c: number | null;
  cusum_neg: number | null;
  cusum_pos: number | null;
  potency: number;
  tau_eq_h: number;
  shelf_life_used_fraction: number;
  mkt_c: number | null;
  trust_level: string;
  verdict: string;
  flags: FrameFlags;
}

/** Something that happened during the run (a check firing, a verdict change, a proposal). */
export interface ScenarioEvent {
  t_s: number;
  type: string;
  payload: Record<string, unknown>;
}

export interface ActionRow {
  name: string;
  cost: number;
  failure_probability: number;
  expected_loss: number;
  cvar: number;
}

export interface DecisionSummary {
  checkpoint_h: number;
  alpha: number;
  n_scenarios: number;
  planner_seed: number;
  actions: ActionRow[];
  chosen_action: string;
  route: string;
  shipment_status: string;
  reasons: string[];
  close_call: boolean;
  close_call_text: string;
  needs_human: boolean;
  trust_level: string;
  verdict: string;
  worst_case_potency: number | null;
  worst_case_shelf_life_used_fraction: number | null;
}

export interface ChainSummary {
  device_id: string;
  key_id: string;
  entries_total: number;
  ok: boolean;
  result: string;
  last_hash_prefix: string | null;
  anchor: null;
  note: string;
}

export interface RoutePoint {
  lat: number;
  lon: number;
  label: string;
}

export interface ReplayMeta {
  schema_version: string;
  scenario_id: string;
  label: string;
  source: string;
  recording: string;
  recording_seed: number | null;
  sample_interval_s: number | null;
  frame_step: number;
  samples_in_recording: number;
  duration_h: number;
  checkpoint_h: number;
  profile: string;
  product: { Ea_over_R: number; T_ref_c: number; tau_max_h: number; P_min: number };
  route: { origin: RoutePoint; destination: RoutePoint; alternative: RoutePoint[] };
  labels: { product: string; data: string };
  software_version: string;
  generated_by: string;
}

export interface ReplayFile {
  meta: ReplayMeta;
  frames: Frame[];
  events: ScenarioEvent[];
  decision: DecisionSummary;
  chain: ChainSummary;
}

export interface ReplayIndexEntry {
  scenario_id: string;
  label: string;
  file: string;
  checkpoint_h: number;
}

export interface ReplayIndex {
  schema_version: string;
  scenarios: ReplayIndexEntry[];
}

/** Chapter 1's bundled figures (story mode), from data generated by our own engine. */
export interface StoryData {
  note: string;
  threshold_c: number;
  journeys: Record<string, { temp_c: number; hours: number }>;
  profiles: Record<
    string,
    {
      label: string;
      Ea_over_R: number;
      tau_max_h: number;
      P_min: number;
      T_ref_c: number;
      journeys: Record<string, { shelf_life_used_percent: number; potency: number; tau_eq_h: number }>;
    }
  >;
}

export type Result<T> = { ok: true; value: T } | { ok: false; error: string };

/** What the screen shows about the data source. */
export type SourceStatus =
  | { state: "loading"; mode: Mode }
  | { state: "ready"; mode: Mode; scenarios: number; message: string | null }
  | { state: "error"; mode: Mode; message: string };

export interface AdapterSnapshot {
  status: SourceStatus;
  index: ReplayIndex | null;
  story: StoryData | null;
  /** Scenario files loaded so far, by scenario id. */
  scenarios: Record<string, ReplayFile>;
}
